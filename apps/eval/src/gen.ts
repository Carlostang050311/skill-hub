import fs from "node:fs";
import path from "node:path";
import type { SkillRecord } from "@skillhub/core";
import type { Scenario } from "./types.js";

// ---------- 覆盖差距 ----------

/** 库中去重后、还没有 scenario 的 skill（agents 来源优先） */
export function uncoveredSkills(records: SkillRecord[], covered: Set<string>): SkillRecord[] {
  const byName = new Map<string, SkillRecord>();
  for (const record of records) {
    const existing = byName.get(record.name);
    if (!existing) {
      byName.set(record.name, record);
      continue;
    }
    const better = (r: SkillRecord): number => (r.source === "agents" ? 0 : 1);
    if (better(record) < better(existing)) byName.set(record.name, record);
  }
  return [...byName.values()].filter((r) => !covered.has(r.name));
}

export interface GenItem {
  name: string;
  description: string;
  bodySnippet: string;
}

/** 组装生成器输入：description 太短或缺失时补正文前 600 字符 */
export function toGenItems(records: SkillRecord[], maxBodyChars = 600): GenItem[] {
  return records.map((r) => {
    let bodySnippet = "";
    if (r.description.trim().length < 30) {
      try {
        bodySnippet = fs.readFileSync(r.skillPath, "utf8").replace(/\r\n/g, "\n").slice(0, maxBodyChars);
      } catch {
        bodySnippet = "";
      }
    }
    return { name: r.name, description: r.description, bodySnippet };
  });
}

// ---------- 分块与提示词 ----------

export interface GenChunk {
  id: string;
  skills: GenItem[];
}

export function buildGenChunks(items: GenItem[], chunkSize = 12): GenChunk[] {
  const chunks: GenChunk[] = [];
  for (let i = 0; i < items.length; i += chunkSize) {
    chunks.push({ id: `gen:${i / chunkSize + 1}`, skills: items.slice(i, i + chunkSize) });
  }
  return chunks;
}

export function renderGenPrompt(chunk: GenChunk): string {
  return [
    "你在为 agent skill 库的评测框架批量生成触发测试用例（scenario）。",
    "",
    "对下面给出的每一个 skill，依据它的 name/description（description 过短时参考 bodySnippet）生成：",
    "- should_trigger：3-4 条「应该触发这个 skill」的用户输入，覆盖 description 里的主要触发词（中英混写的 description 就两种语言都出用例），口吻像真实用户随口提需求",
    "- should_not_trigger：2-3 条「不应该触发」的相近但超边界的用户输入（相邻领域、只沾一点点边的请求）",
    "",
    "硬性要求：只给清单里的 skill 生成，一个不多一个不少；用例必须和 description 强相关，不要泛泛的通用句。",
    "",
    "skill 清单（JSON）：",
    JSON.stringify(chunk.skills, null, 2),
    "",
    '只输出 JSON（不要围栏、不要其他文字）：{"scenarios": [{"skill": "<name，原样照抄>", "should_trigger": ["..."], "should_not_trigger": ["..."]}]}',
  ].join("\n");
}

// ---------- 结果解析与校验 ----------

export interface GenOutcome {
  generated: Scenario[];
  invalid: Array<{ skill: string; reason: string }>;
}

export function parseGenResults(raw: string, validNames: Set<string>): GenOutcome {
  const outcome: GenOutcome = { generated: [], invalid: [] };
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    // 容忍围栏与前后杂文：截取最外层 JSON
    const start = raw.indexOf("{");
    const end = raw.lastIndexOf("}");
    try {
      parsed = JSON.parse(raw.slice(start, end + 1));
    } catch {
      outcome.invalid.push({ skill: "(整块)", reason: "输出无法解析为 JSON" });
      return outcome;
    }
  }
  const list = (parsed as { scenarios?: unknown }).scenarios;
  if (!Array.isArray(list)) {
    outcome.invalid.push({ skill: "(整块)", reason: "缺少 scenarios 数组" });
    return outcome;
  }
  for (const item of list) {
    const map = item as Record<string, unknown>;
    const skill = typeof map.skill === "string" ? map.skill.trim() : "";
    const trigger = Array.isArray(map.should_trigger)
      ? (map.should_trigger as unknown[]).filter((x): x is string => typeof x === "string" && x.trim().length > 0).map((x) => x.trim())
      : [];
    const notTrigger = Array.isArray(map.should_not_trigger)
      ? (map.should_not_trigger as unknown[]).filter((x): x is string => typeof x === "string" && x.trim().length > 0).map((x) => x.trim())
      : [];
    if (!skill || !validNames.has(skill)) {
      if (skill) outcome.invalid.push({ skill, reason: "不在本次清单里" });
      continue;
    }
    if (trigger.length === 0 || notTrigger.length === 0) {
      outcome.invalid.push({ skill, reason: "正例或反例为空" });
      continue;
    }
    outcome.generated.push({
      skill,
      shouldTrigger: trigger,
      shouldNotTrigger: notTrigger,
      raw: undefined,
    });
  }
  return outcome;
}

// ---------- YAML 输出 ----------

const HEADER = "# auto-generated by skillhub-eval gen —— 请人工过目后删除本行";

/** 输出 YAML；字符串统一走 JSON 转义（兼容 YAML 双引号标量） */
export function scenarioToYaml(scenario: Scenario, withHeader = true): string {
  const lines: string[] = [];
  if (withHeader) lines.push(HEADER);
  lines.push(`skill: ${JSON.stringify(scenario.skill)}`);
  lines.push("should_trigger:");
  for (const item of scenario.shouldTrigger) lines.push(`  - ${JSON.stringify(item)}`);
  lines.push("should_not_trigger:");
  for (const item of scenario.shouldNotTrigger) lines.push(`  - ${JSON.stringify(item)}`);
  return lines.join("\n") + "\n";
}

export function writeScenarioFile(dir: string, scenario: Scenario): string {
  fs.mkdirSync(dir, { recursive: true });
  // skill 名可能含 :: 等文件系统非法字符；YAML 内的 skill 字段保持原名
  const safeName = scenario.skill.replace(/[^a-zA-Z0-9._-]/g, "_");
  const file = path.join(dir, `${safeName}.yaml`);
  fs.writeFileSync(file, scenarioToYaml(scenario), "utf8");
  return file;
}
